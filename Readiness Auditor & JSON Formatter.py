#!/usr/bin/env python3
"""
HPE Morpheus Demo - Task 2: Python 3.13 Compliance & Readiness Audit
Designed for Debian 13 (Trixie) running Python 3.13.x
"""

import json
import os
import platform
import shutil
import socket
import sys
from datetime import datetime, timezone
from pathlib import Path

BASELINE_PATH = Path("/tmp/morpheus_demo/os_baseline.json")
REPORT_PATH = Path("/tmp/morpheus_demo/final_audit_report.json")


def log_info(msg: str) -> None:
    """Log progress to stderr so stdout stays clean for Morpheus JSON Result parsing."""
    print(f"[Python-Audit] {msg}", file=sys.stderr)


def collect_system_metrics() -> dict:
    # 1. Verify Python 3.13 runtime details
    py_version = platform.python_version()
    py_impl = platform.python_implementation()

    # Check if Free-Threaded (GIL-disabled) build is active (Python 3.13+ feature)
    gil_enabled = True
    if hasattr(sys, "_is_gil_enabled"):
        gil_enabled = sys._is_gil_enabled()

    # 2. Read OS release info via standard library (Python 3.10+ / 3.13 standard)
    try:
        os_info = platform.freedesktop_os_release()
    except OSError:
        os_info = {"PRETTY_NAME": "Unknown Linux", "VERSION_CODENAME": "unknown"}

    # 3. Calculate Root Disk Usage
    total, used, free = shutil.disk_usage("/")
    disk_used_pct = round((used / total) * 100, 2)

    # 4. Read Memory Info from /proc/meminfo
    mem_info = {}
    with open("/proc/meminfo", "r", encoding="utf-8") as f:
        for line in f:
            parts = line.split(":")
            if len(parts) == 2:
                key = parts[0].strip()
                val = parts[1].strip().split()[0]
                if key in ("MemTotal", "MemAvailable"):
                    mem_info[key] = int(val)

    mem_total_mb = round(mem_info.get("MemTotal", 0) / 1024, 1)
    mem_avail_mb = round(mem_info.get("MemAvailable", 0) / 1024, 1)

    return {
        "os_pretty_name": os_info.get("PRETTY_NAME"),
        "os_codename": os_info.get("VERSION_CODENAME", "trixie"),
        "python_runtime": {
            "version": py_version,
            "implementation": py_impl,
            "is_3_13_or_newer": sys.version_info >= (3, 13),
            "gil_enabled": gil_enabled,
        },
        "resources": {
            "cpu_count": os.cpu_count(),
            "memory_total_mb": mem_total_mb,
            "memory_available_mb": mem_avail_mb,
            "root_disk_used_percent": disk_used_pct,
        },
        "network": {
            "fqdn": socket.getfqdn(),
            "primary_ip": socket.gethostbyname(socket.gethostname()),
        },
    }


def main() -> int:
    log_info(f"Executing audit using Python {platform.python_version()}")

    # Load baseline generated by Task 1 (Shell script)
    baseline_data = {}
    if BASELINE_PATH.exists():
        log_info(f"Loading Task 1 baseline from {BASELINE_PATH}")
        baseline_data = json.loads(BASELINE_PATH.read_text(encoding="utf-8"))
    else:
        log_info("Warning: Task 1 baseline file not found. Proceeding standalone.")

    # Gather live Python 3.13 telemetry
    audit_data = collect_system_metrics()

    # Evaluate compliance gates
    checks = {
        "debian_trixie_verified": audit_data["os_codename"] == "trixie",
        "python_3_13_verified": audit_data["python_runtime"]["is_3_13_or_newer"],
        "disk_space_healthy": audit_data["resources"]["root_disk_used_percent"] < 85.0,
        "task1_handoff_success": bool(baseline_data.get("motd_configured", False)),
    }
    overall_status = "PASSED" if all(checks.values()) else "WARNING"

    # Combine into final payload
    final_payload = {
        "workflow_status": overall_status,
        "audited_at_utc": datetime.now(timezone.utc).isoformat(),
        "compliance_checks": checks,
        "task1_baseline": baseline_data,
        "task2_telemetry": audit_data,
    }

    # Save artifact on the VM
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(json.dumps(final_payload, indent=2), encoding="utf-8")
    log_info(f"Saved full audit artifact to {REPORT_PATH}")

    # Output clean JSON to stdout for Morpheus Task Results capture
    print(json.dumps(final_payload, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
